function print_summary(label, res)
% PRINT_SUMMARY  One-paragraph summary of an optimization run (res from the
% shapeopt_* drivers), in the quantities of the tables of the paper.
if res.cfg.tol_eta > 0, alg = 'screened ROM (Algorithm 2)'; else, alg = 'full order (Algorithm 1)'; end
pcm = NaN; if ~isempty(res.pc_its), pcm = mean(res.pc_its); end
fprintf(['\n[%s, %s] %d iterations, %.1f s\n' ...
         '  FOM/ROM solves: %d+%d / %d (fallbacks incl. warm-up + verifications [%d estimate-triggered] / accepted reduced)\n' ...
         '  factorizations %d; retained-factor GMRES solves %d (mean %.1f iterations, %d refreshes, %d failed)\n' ...
         '  J: %.7e -> %.7e (%.2f%%); volume error <= %.1e cells\n'], ...
    label, alg, res.iters, res.time, res.n_fom, res.n_verify, res.n_rom, res.n_verify_dwr, ...
    res.nfact, res.n_pc, pcm, res.n_refresh, res.n_pc_fail, ...
    res.J(1), res.J(end), 100*(res.J(1) - res.J(end))/res.J(1), res.volerr_max);
end
